fun stringsForLanguage(code: String): AppStrings {
    return if (code == AppLanguage.ARABIC.code) ArabicStrings else EnglishStrings
}

fun localizeShotType(rawType: String, strings: AppStrings): String {
    return strings.shotTypeDisplayNames[rawType] ?: rawType
